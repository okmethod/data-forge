-- 年齢3区分×男女別人口を都道府県粒度へ集約（デモの公開粒度＝都道府県まで）。
-- 出所テーブルはアトム（市区町村など level3/4/6）で全国を過不足なく分割被覆するため、
-- area_code 先頭2桁で県へ束ねれば県内合計＝真の県人口（県境は不変）。
-- ★これは「表現の集約」＝ダッシュボード側の責務（パイプラインの正典データはアトム粒度のまま）。
-- ★Evidence はソースの結果 parquet を公開ビルドに丸ごと同梱するため、ここで県粒度へ畳んで
--   市区町村グレイン（数万行）が公開ビルドへ流出しないようにする（sample_cities.sql と同じ考え方）。
-- 県名は 2020 断面から確定した固定表を埋め込む（パイプの正典昇格分と同値・当面ダッシュ側で維持）。
with pref(pref_code, pref_name) as (
  values
    ('01','北海道'), ('02','青森県'), ('03','岩手県'), ('04','宮城県'), ('05','秋田県'),
    ('06','山形県'), ('07','福島県'), ('08','茨城県'), ('09','栃木県'), ('10','群馬県'),
    ('11','埼玉県'), ('12','千葉県'), ('13','東京都'), ('14','神奈川県'), ('15','新潟県'),
    ('16','富山県'), ('17','石川県'), ('18','福井県'), ('19','山梨県'), ('20','長野県'),
    ('21','岐阜県'), ('22','静岡県'), ('23','愛知県'), ('24','三重県'), ('25','滋賀県'),
    ('26','京都府'), ('27','大阪府'), ('28','兵庫県'), ('29','奈良県'), ('30','和歌山県'),
    ('31','鳥取県'), ('32','島根県'), ('33','岡山県'), ('34','広島県'), ('35','山口県'),
    ('36','徳島県'), ('37','香川県'), ('38','愛媛県'), ('39','高知県'), ('40','福岡県'),
    ('41','佐賀県'), ('42','長崎県'), ('43','熊本県'), ('44','大分県'), ('45','宮崎県'),
    ('46','鹿児島県'), ('47','沖縄県')
)
select
  p.pref_code,
  p.pref_name,
  t.year,
  t.sex_code,
  t.sex,
  t.age_class_code,
  t.age_class,
  sum(t.population) as population
from population_by_age t
join pref p on substr(t.area_code, 1, 2) = p.pref_code
group by p.pref_code, p.pref_name, t.year, t.sex_code, t.sex, t.age_class_code, t.age_class
